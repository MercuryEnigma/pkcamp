/**
 * Sprite manifest types and a small placeholder/fixture manifest.
 *
 * This module is intentionally private to `src/services/sprites`. It is not a
 * hand-authored data format for consumers — a future developer-only
 * extraction/generation tool is a separate, still-ungated concern (see
 * ROADMAP.md, "Shared sprite service"). Nothing here contains real Pokémon
 * artwork; `assetPath` values are placeholder strings only, shaped like the
 * `import.meta.env.BASE_URL`-relative convention real assets would use later.
 */
import type { SpriteAttribution } from './attribution'

/** Gender variants a manifest entry can be scoped to. */
export type SpriteGender = 'male' | 'female' | 'genderless'

/**
 * A single verified sprite asset entry.
 *
 * - `form` is omitted (or left `undefined`) for the base/default form.
 * - `gender` is omitted when the art does not differ by gender.
 * - `assetPath` may be BASE_URL-relative for bundled art or an HTTPS URL for
 *   a configured remote source.
 */
export interface SpriteManifestEntry {
  nationalDex: number
  form?: string
  gender?: SpriteGender
  shiny: boolean
  egg: boolean
  attribution?: SpriteAttribution
  assetPath: string
}

export type SpriteManifest = ReadonlyArray<SpriteManifestEntry>

/** National Pokédex through Pecharunt (Generation IX). */
export const SUPPORTED_DEX_RANGE = { min: 1, max: 1025 } as const

/** A form index from save data mapped to a source-independent form id. */
export type SpriteFormAliases = Readonly<
  Record<number, Readonly<Record<number, string>>>
>

export interface SpriteCoverageBucket<T extends number | string> {
  available: readonly T[]
  missing: readonly T[]
}

/** Auditable coverage for every variant axis supported by the resolver. */
export interface SpriteSourceCoverage {
  base: SpriteCoverageBucket<number>
  shiny: SpriteCoverageBucket<number>
  forms: SpriteCoverageBucket<string>
  shinyForms: SpriteCoverageBucket<string>
  female: SpriteCoverageBucket<string>
  shinyFemale: SpriteCoverageBucket<string>
}

/** A selectable sprite source and the gaps it is known to have. */
export interface SpriteSourceDefinition {
  id: string
  label: string
  /** Where this source's art actually lives, for attribution/browsing. */
  homepage: string
  manifest: SpriteManifest
  formAliases?: SpriteFormAliases
  coverage: SpriteSourceCoverage
}


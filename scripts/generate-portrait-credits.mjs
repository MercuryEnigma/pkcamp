import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

// SpriteCollab credits are scoped to a portrait set (including form, shiny,
// and gender), not to an individual emotion. Preserve all named contributors.
export async function generatePortraitCredits(tracker, namesText) {
  const names = new Map(
    namesText
      .trim()
      .split(/\r?\n/)
      .slice(1)
      .map((row) => {
        const [name, id] = row.split('\t')
        return [id, name]
      })
  )
  const credits = {}
  function visit(nodes, parent = '') {
    for (const [key, node] of Object.entries(nodes)) {
      const path = parent ? `${parent}/${key}` : key
      const credit = node.portrait_credit
      const artists = [
        ...new Set(
          [credit?.primary, ...(credit?.secondary ?? [])]
            .map((id) => names.get(id)?.trim())
            .filter(Boolean)
        ),
      ]
      if (artists.length) credits[`${path}/Normal.png`] = artists.join(', ')
      visit(node.subgroups ?? {}, path)
    }
  }
  visit(tracker)
  await writeFile(
    new URL(
      '../src/services/sprites/generatedPortraitCredits.ts',
      import.meta.url
    ),
    `// Generated by scripts/generate-portrait-credits.mjs from SpriteCollab tracker.json\n// and credit_names.txt. Credits apply to the portrait set. Do not hand-edit.\nexport const PORTRAIT_CREDITS: Readonly<Record<string, string>> = ${JSON.stringify(credits, null, 2)}\n`
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [tracker, names] = process.argv.slice(2)
  await generatePortraitCredits(
    JSON.parse(await readFile(tracker, 'utf8')),
    await readFile(names, 'utf8')
  )
}
